let sink: PixelSink | null = null;

export function bindPixels(fn: PixelSink | null): void {
  sink = fn;
}

export function measureText(text: string, scale: number): number {
  const lines = text.split('\n');
  let widest = 0;
  for (const line of lines) {
    if (line.length > 0) {
      widest = Math.max(widest, (line.length * FONT_ADVANCE - 1) * scale);
    }
  }
  return widest;
}

export function measureHeight(text: string, scale: number): number {
  const lines = text.split('\n');
  return lines.length * FONT_HEIGHT * scale + (lines.length - 1) * FONT_LINE_GAP * scale;
}

export function drawText(px: number, py: number, text: string, scale: number, color: number): number {
  if (!sink) throw new Error('font: bindPixels() must be called before drawText()');
  const paint = sink;
  let x = px;
  let y = py;
  let widest = 0;
  let lineStart = px;

  for (const ch of text) {
    if (ch === '\n') {
      widest = Math.max(widest, x - lineStart - (x === lineStart ? 0 : FONT_ADVANCE * scale));
      x = px;
      lineStart = px;
      y += (FONT_HEIGHT + FONT_LINE_GAP) * scale;
      continue;
    }
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    for (let row = 0; row < FONT_HEIGHT; row++) {
      const bits = glyph[row];
      for (let col = 0; col < FONT_WIDTH; col++) {
        if (bits[col] !== '#') continue;
        const bx = x + col * scale;
        const by = y + row * scale;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            paint(bx + dx, by + dy, color);
          }
        }
      }
    }
    x += FONT_ADVANCE * scale;
  }

  widest = Math.max(widest, x - lineStart - (x === lineStart ? 0 : FONT_ADVANCE * scale));
  return widest;
}

export function wrapText(text: string, maxWidth: number, scale: number): string[] {
  const words = text.trim().split(/\s+/).filter((word) => word.length > 0);
  if (words.length === 0) return [''];

  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    const candidate = current.length === 0 ? word : current + ' ' + word;
    if (current.length === 0 || measureText(candidate, scale) <= maxWidth) {
      current = candidate;
    } else {
      lines.push(current);
      current = word;
    }
  }
  if (current.length > 0) lines.push(current);

  if (lines.length > 1) {
    const lastWords = lines[lines.length - 1].split(' ');
    if (lastWords.length === 1) {
      const prevWords = lines[lines.length - 2].split(' ');
      if (prevWords.length > 1) {
        const moved = prevWords[prevWords.length - 1];
        const candidate = moved + ' ' + lines[lines.length - 1];
        if (measureText(candidate, scale) <= maxWidth) {
          lines[lines.length - 2] = prevWords.slice(0, -1).join(' ');
          lines[lines.length - 1] = candidate;
        }
      }
    }
  }

  return lines;
}
